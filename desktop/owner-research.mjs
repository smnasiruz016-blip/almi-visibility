import { inflateRawSync } from "node:zlib";

/** the text of the document (paragraphs on their own lines) */
export function documentText(name, bytes) {
  const n = String(name ?? "").toLowerCase(), b = Buffer.from(bytes ?? []);
  if (/\.(?:txt|md|csv)$/.test(n)) return b.toString("utf8").replace(/^﻿/, "");
  const inner = /\.odt$/.test(n) ? "content.xml" : /\.docx$/.test(n) ? "word/document.xml" : null; if (!inner) return null;
  const xml = zipEntry(b, inner); if (xml === null) return null;
  return decodeXml(xml.replace(/<text:line-break\/>|<w:br\/>/g, "\n").replace(/<\/(?:text:p|text:h|w:p)>/g, "\n").replace(/<text:tab\/>|<w:tab\/>/g, " ").replace(/<text:a\b[^>]*xlink:href="([^"]+)"[^>]*>/g, " $1 ").replace(/<[^>]+>/g, "")).replace(/[ \t]+/g, " ").replace(/\n\s*\n+/g, "\n\n").trim();
}
const decodeXml = (s) => s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d))).replace(/&amp;/g, "&");
/** one file of a zip (stored or deflated), read from its central directory; null when it is not there */
export function zipEntry(buf, want) {
  let eocd = -1; for (let i = buf.length - 22; i >= Math.max(0, buf.length - 66000); i--) if (buf.readUInt32LE(i) === 0x06054b50) { eocd = i; break; } if (eocd < 0) return null;
  let p = buf.readUInt32LE(eocd + 16); const count = buf.readUInt16LE(eocd + 10);
  for (let k = 0; k < count && p + 46 <= buf.length; k++) {
    if (buf.readUInt32LE(p) !== 0x02014b50) return null;
    const method = buf.readUInt16LE(p + 10), size = buf.readUInt32LE(p + 20), nameLen = buf.readUInt16LE(p + 28), extra = buf.readUInt16LE(p + 30), comment = buf.readUInt16LE(p + 32), local = buf.readUInt32LE(p + 42), name = buf.toString("utf8", p + 46, p + 46 + nameLen);
    if (name === want) { const lp = local, start = lp + 30 + buf.readUInt16LE(lp + 26) + buf.readUInt16LE(lp + 28), data = buf.subarray(start, start + size); return (method === 0 ? data : method === 8 ? inflateRawSync(data) : null)?.toString("utf8") ?? null; }
    p += 46 + nameLen + extra + comment;
  }
  return null;
}

const URL_RE = /https?:\/\/[^\s<>"')\]]+/g;
const AI_SUMMARY = /\b(?:AI Overview|AI Mode|generated by AI|AI[- ]generated|according to (?:ChatGPT|Gemini|Copilot|Claude|Perplexity)|(?:ChatGPT|Gemini|Copilot|Perplexity) (?:says|said|answered))\b/i;
const NOT_A_SOURCE = (u) => { try { const x = new URL(u); return /(^|\.)google\.[a-z.]+$/.test(x.hostname) && /^\/search/.test(x.pathname) ? "a search-results page is never a source" : /(^|\.)(?:chatgpt\.com|chat\.openai\.com|gemini\.google\.com|perplexity\.ai|copilot\.microsoft\.com)$/.test(x.hostname) ? "an AI assistant's answer is never a source" : null; } catch { return "not a page address"; } };

/** the document's text → { rows: [{ question, answer, link }], refused: [{ question, why }] } */
export function researchRows(text) {
  const lines = String(text ?? "").split(/\n/).map((l) => l.trim()), rows = [], refused = [];
  let q = null, body = [];
  const close = () => {
    if (!q) return; const all = body.join(" ").trim(), links = [...new Set(all.match(URL_RE) ?? [])].map((u) => u.replace(/[.,;:]+$/, "")), answer = all.replace(URL_RE, " ").replace(/\b(?:Source|Sources|Link|Read on|Checked)\s*:\s*/gi, " ").replace(/\s+/g, " ").replace(/\s+([.,;:])/g, "$1").trim();
    if (!answer) refused.push({ question: q, why: "no answer under it" });
    else if (AI_SUMMARY.test(all)) refused.push({ question: q, why: "an AI summary (for example a Google AI Overview) is never a source" });
    else { const good = links.filter((u) => !NOT_A_SOURCE(u)); if (!good.length) refused.push({ question: q, why: links.length ? NOT_A_SOURCE(links[0]) : "no page address: a line needs the page it came from" }); else rows.push({ question: q, answer: answer.slice(0, 600), link: good[0] }); }
    q = null; body = [];
  };
  for (const l of lines) { if (!l) continue; const m = /^(?:Q\d*[.:)]?\s*|\d+[.)]\s*)?(.{8,240}\?)\s*$/.exec(l); if (m) { close(); q = m[1].trim(); continue; } if (q) body.push(l); }
  close();
  return { rows, refused };
}

/** kept rows join the plan as UNCHECKED lines under the page item that asks the same question; the truth pass decides */
const norm = (s) => String(s ?? "").toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
export function addOwnerResearch(plan, rows = [], { on = new Date().toISOString().slice(0, 10) } = {}) {
  let joined = 0; const waiting = [];
  for (const r of rows) {
    let hit = false; for (const p of plan?.pages ?? []) for (const it of p.items ?? []) if (norm(it.question) === norm(r.question) && !(it.claims ?? []).some((c) => norm(c.text) === norm(r.answer))) { (it.claims ??= []).push({ claimId: `research-${norm(r.question).slice(0, 40).replace(/ /g, "-")}`, card: null, text: r.answer, link: r.link, readOn: String(r.on ?? on).slice(0, 10), source: `${(() => { try { return new URL(r.link).hostname.replace(/^www./, ""); } catch { return "its page"; } })()} — its page`, official: false, research: true /* the source shown is the page itself, never "your research" */ }); hit = true; }
    if (hit) joined++; else waiting.push(r.question);
  }
  return { joined, waiting };
}
